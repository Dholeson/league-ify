#!/usr/bin/env tsx
// Turn the local JSON database into SQL that D1 can swallow.
//
//   npx tsx scripts/export-to-d1.ts                 -> data/d1-seed.sql
//   npx tsx scripts/export-to-d1.ts out.sql
//
// Then apply it:
//   npx wrangler d1 execute dhole-workshop --local  --file=migrations/0001_league_ify.sql
//   npx wrangler d1 execute dhole-workshop --local  --file=data/d1-seed.sql
//   ...and the same two with --remote when you are ready.
//
// THE OUTPUT CONTAINS REAL MATCH DATA. It defaults into data/, which is
// gitignored, and it should stay there. Do not move it next to the migrations:
// migrations/ is committed, this is your ranked history.
//
// The split mirrors the adapter exactly — document rows for everything except
// matches, one row per match with its array position — because the point of
// this script is to produce a database the adapter can read back unchanged.
// scripts/verify-d1-roundtrip.ts is what proves it did.

import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { dirname, resolve, basename } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const DATA_DIR = resolve(__dirname, "..", "data");
const PROFILES_DIR = resolve(DATA_DIR, "profiles");

const now = Math.floor(Date.now() / 1000);

// SQLite string literal: double every single quote. Every value that reaches
// the output goes through here, because a Riot ID or a champion nickname with
// an apostrophe would otherwise end the statement early.
function q(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

interface MatchLike { id?: unknown; [k: string]: unknown; }

function readJson<T>(file: string): T | null {
  if (!existsSync(file)) return null;
  try {
    return JSON.parse(readFileSync(file, "utf8")) as T;
  } catch (err) {
    console.error(`  ! ${basename(file)} is not valid JSON — skipped (${(err as Error).message})`);
    return null;
  }
}

const lines: string[] = [];
const stats: Array<{ key: string; matches: number; bodyBytes: number }> = [];

function emitDocument(key: string, doc: Record<string, unknown> | null) {
  if (!doc) return;

  const rawMatches = Array.isArray(doc.matches) ? (doc.matches as MatchLike[]) : undefined;
  const { matches: _drop, ...withoutMatches } = doc;

  // Same rule as the adapter: an empty array stays in the body so that "no
  // games yet" stays distinguishable from "this document has no matches key".
  const body: Record<string, unknown> =
    rawMatches && rawMatches.length === 0 ? { ...withoutMatches, matches: [] } : withoutMatches;

  const bodyText = JSON.stringify(body);
  lines.push(
    `INSERT INTO documents (doc_key, body, updated_at) VALUES (${q(key)}, ${q(bodyText)}, ${now})\n` +
    `  ON CONFLICT(doc_key) DO UPDATE SET body = excluded.body, updated_at = excluded.updated_at;`
  );

  let written = 0;
  let skipped = 0;
  const seen = new Set<string>();

  rawMatches?.forEach((m, index) => {
    const id = m?.id;
    if (typeof id !== "string" || !id) { skipped++; return; }
    // (doc_key, match_id) is the primary key, so a duplicate id in the source
    // array would collide. Keep the first and say so rather than letting the
    // upsert silently overwrite it.
    if (seen.has(id)) { skipped++; return; }
    seen.add(id);
    lines.push(
      `INSERT INTO matches (doc_key, match_id, ord, body, updated_at) VALUES ` +
      `(${q(key)}, ${q(id)}, ${index}, ${q(JSON.stringify(m))}, ${now})\n` +
      `  ON CONFLICT(doc_key, match_id) DO UPDATE SET ord = excluded.ord, body = excluded.body, updated_at = excluded.updated_at;`
    );
    written++;
  });

  if (skipped) console.error(`  ! ${key}: skipped ${skipped} match(es) with a missing or duplicate id`);
  stats.push({ key, matches: written, bodyBytes: bodyText.length });
}

console.log("reading local database...");

emitDocument("live",    readJson(resolve(DATA_DIR, "league-ify.json")));
emitDocument("demo",    readJson(resolve(DATA_DIR, "league-ify.demo.json")));
emitDocument("profile", readJson(resolve(DATA_DIR, "league-ify.profile.json")));
emitDocument("meta",    readJson(resolve(DATA_DIR, "league-ify.meta.json")));

if (existsSync(PROFILES_DIR)) {
  for (const file of readdirSync(PROFILES_DIR)) {
    if (!file.endsWith(".json")) continue;
    const name = file.slice(0, -".json".length);
    if (!/^[a-z0-9_-]+$/i.test(name)) {
      console.error(`  ! profiles/${file}: name is not a safe document key — skipped`);
      continue;
    }
    emitDocument(`profiles/${name}`, readJson(resolve(PROFILES_DIR, file)));
  }
}

const out = process.argv[2] ?? resolve(DATA_DIR, "d1-seed.sql");
const header = [
  "-- Generated by scripts/export-to-d1.ts. Do not edit, do not commit.",
  "-- Contains real match history. data/ is gitignored; keep it there.",
  `-- Documents: ${stats.length}. Matches: ${stats.reduce((n, s) => n + s.matches, 0)}.`,
  "",
].join("\n");

writeFileSync(out, header + lines.join("\n") + "\n", "utf8");

console.log("");
for (const s of stats) {
  console.log(`  ${s.key.padEnd(28)} body ${String(s.bodyBytes).padStart(7)} B   matches ${s.matches}`);
}
console.log(`\nwrote ${out}`);
console.log(`${lines.length} statements`);
